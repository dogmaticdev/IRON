section .text
    global clear_whitespace

    ;r8 write pointer
    ;r9 read pointer
    ;10 end pointer
    ;rdx string length
    ;rcx count
    ;rax bitmask
    ;rdi offset
    ;rsi bool

clear_whitespace:
    ; ── Allocate Pointers ────────────────────────────────────────────────────
    mov r8, [input_pointer]
    mov r9, [input_pointer]
    mov r10, [input_pointer]
    add r10, [input_size]


    ; ── Setup Registers ──────────────────────────────────────────────────────

    movdqa xmm1, [despace]
    movdqa xmm2, [index0]
    movdqa xmm15, [sign]
    xor rcx, rcx
    xor rdx, rdx
    xor rdi, rdi
    xor rsi, rsi
    jmp .main_loop

.clear:
    cmp rsi, 0
    je .main_loop
    mov byte [r8], 0x00
    inc r8
    xor rsi, rsi

.main_loop:

    cmp r9, r10
    jge .end

    movdqa xmm3, [r9]
    add r9, 16

    pxor   xmm14, xmm14
    movdqa   xmm4, xmm3
    movdqa   xmm5, xmm3
    psubusb  xmm5, xmm15
    pcmpgtb  xmm14, xmm5
    pcmpgtb  xmm4, xmm1
    por      xmm4, xmm14
    pmovmskb eax, xmm4
    pand     xmm4, xmm3
    cmp      ax, 0xFFFF
    jz .full

    tzcnt    cx, ax
    jc .clear
    jz .skip

    shr      ax, cl
    test     sil, sil
    jz .check
    dec      cx
    inc      dx
    test     cx, cx
    jnz .check

.skip:
    xor edi, edi
    movdqa   xmm5, xmm2
    jmp .next

.check:
    mov      edi, ecx
    shl      ecx, 4
    movdqa   xmm5, [index0 + rcx]
.next:
    not      ax
    tzcnt    cx, ax
    not      ax

    inc      cx
    shr      ax, cl
    add      dx, cx
    dec      cx
    add      cl, sil
    xor      rsi, rsi
    shl      ecx, 4
    movdqa   xmm0, [bitmask0 + rcx]

.string_loop:
    xor      ecx, ecx
    tzcnt    cx, ax
    jc .end_loop
    jz .skip2

    add      di, cx
    shr      ax, cl
    mov      ecx, edi
    shl      ecx, 4
    movdqa   xmm6, [index0 + rcx]
    pblendvb xmm5, xmm6

.skip2:
    not      ax
    tzcnt    cx, ax
    not      ax

    inc      cx
    shr      ax, cl
    add      dx, cx
    mov      cx, dx
    dec      cx

    shl ecx, 4
    movdqa   xmm0, [bitmask0 + rcx]

    jmp .string_loop

.end_loop:
    lea      ecx, [edx + edi]
    xor      edi, edi
    cmp      ecx, 17
    setz sil
    sub      edx, esi

    pshufb   xmm4, xmm5
    movdqu   [r8], xmm4
    add      r8, rdx
    xor      edx, edx
    jmp .main_loop

.full:
    movdqu   [r8], xmm3
    mov      rsi, 1
    add      r8, 16
    jmp .main_loop

.end:
    pxor xmm0, xmm0
    movdqu [r8], xmm0
    sub r8, [input_pointer]
    mov [input_size], r8
    ret
